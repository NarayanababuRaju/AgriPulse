import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:hive_flutter/hive_flutter.dart';
import 'package:firebase_core/firebase_core.dart';
import 'core/theme/app_theme.dart';
import 'core/router/app_router.dart';
import 'firebase_options.dart'; // Will be generated by flutterfire configure
import 'features/crop_diagnosis/models/diagnosis_record.dart';
import 'features/yield_prediction/models/yield_record.dart';
import 'core/models/weather_cache.dart';
import 'core/services/local_vault.dart';
import 'features/crop_diagnosis/models/thread_item.dart';

import 'package:intl/date_symbol_data_local.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await initializeDateFormatting(); // Fix for LocaleDataException
  debugPrint("🚀 AgriPulse: Widgets & Locale initialized.");
  
  // Initialize Hive for local caching
  try {
    await Hive.initFlutter();
    debugPrint("✅ AgriPulse: Hive initialized.");
  } catch (e) {
    debugPrint("❌ AgriPulse: Hive failed: $e");
  }
  
  // Register Adapters (Type IDs: 0, 1, 2, 3)
  Hive.registerAdapter(DiagnosisRecordAdapter());
  Hive.registerAdapter(YieldRecordAdapter());
  Hive.registerAdapter(WeatherCacheAdapter());
  Hive.registerAdapter(ThreadItemAdapter());
  
  // Initialize LocalVault Service
  try {
    await LocalVault().init();
    debugPrint("✅ AgriPulse: LocalVault initialized.");
  } catch (e) {
    debugPrint("❌ AgriPulse: LocalVault failed: $e");
  }
  
  // Initialize Firebase with the generated options
  try {
    await Firebase.initializeApp(
      options: DefaultFirebaseOptions.currentPlatform,
    );
    debugPrint("✅ AgriPulse: Firebase initialized successfully.");
  } catch (e) {
    debugPrint("❌ Firebase initialization failed: $e");
  }

  runApp(
    const ProviderScope(
      child: AgriPulseApp(),
    ),
  );
}

class AgriPulseApp extends ConsumerWidget {
  const AgriPulseApp({super.key});

  @override
  Widget build(BuildContext context, WidgetRef ref) {
    final router = ref.watch(routerProvider);
    
    return MaterialApp.router(
      title: 'AgriPulse - Intelligent Farming',
      debugShowCheckedModeBanner: false,
      
      // Theme Configuration with specialized "Earth & Growth" palette
      theme: AppTheme.lightTheme,
      
      // Routing
      routerConfig: router,
    );
  }
}
